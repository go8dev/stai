def test_starting_and_using_the_app_creates_nothing(
    fresh: tuple[str, Engine], make_harness: AppFactory
) -> None:
    url, engine = fresh
    harness = make_harness(DATABASE_URL=url)

    assert harness.client.get("/api/healthz").status_code == 200
    assert harness.client.get("/api/auth/user").status_code == 200
    assert harness.client.get("/api/system/status").status_code == 401
    # Signing in needs the tables. Without them it fails; it does not create them.
    response = sign_in(harness.client, harness.provider)
    assert response.status_code in (302, 503)
    assert "sid" not in harness.client.cookies

    assert public_tables(engine) == set()


def test_the_app_has_no_code_that_creates_tables() -> None:
    package = API_ROOT / "stai"
    offenders = [
        str(path.relative_to(API_ROOT))
        for path in sorted(package.rglob("*.py"))
        if re.search(
            r"\.create_all\(|\.drop_all\(|CreateTable\(|CREATE\s+TABLE|"
            r"^\s*(from|import)\s+alembic",
            path.read_text(encoding="utf-8"),
            re.MULTILINE,
        )
    ]

    assert offenders == []
