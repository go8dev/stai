FORBIDDEN_IN_REVISIONS = [
    r"create\s+(or\s+replace\s+)?(constraint\s+)?trigger",
    r"create\s+(or\s+replace\s+)?(function|procedure)",
    r"create\s+extension",
    r"create\s+schema",
    r"create\s+(or\s+replace\s+)?rule",
    r"create\s+policy",
    r"\bgrant\s",
    r"\brevoke\s",
    r"schema\s*=",
    r"sa\.float|sa\.real|double_precision|sa\.double",
    r"datetime\(\s*\)|timezone\s*=\s*false",
    r"\bfrom\s+stai\b|\bimport\s+stai\b",
]


@pytest.mark.parametrize("pattern", FORBIDDEN_IN_REVISIONS)
def test_no_revision_contains(pattern: str) -> None:
    files = sorted(VERSIONS.glob("*.py"))
    assert files

    for path in files:
        assert not re.search(pattern, path.read_text(encoding="utf-8"), re.IGNORECASE), path.name


# -- where migrations may run -----------------------------------------------------------------


def from_environment() -> Config:
    """The configuration `pnpm run db:migrate` uses: the address comes from the environment."""
    return Config(str(API_ROOT / "alembic.ini"))


def test_migrations_take_the_database_from_the_environment_in_development(
    fresh: tuple[str, Engine], clean_environment: pytest.MonkeyPatch
) -> None:
    url, engine = fresh
    clean_environment.setenv("DATABASE_URL", url)

    command.upgrade(from_environment(), "head")

    assert public_tables(engine) == APPLICATION_TABLES | {"alembic_version"}


@pytest.mark.parametrize("action", ["upgrade", "downgrade", "check", "current", "stamp"])
def test_migrations_refuse_to_run_on_the_published_machine(
    fresh: tuple[str, Engine], clean_environment: pytest.MonkeyPatch, action: str
) -> None:
    url, engine = fresh
    clean_environment.setenv("DATABASE_URL", url)
    clean_environment.setenv("REPLIT_DEPLOYMENT", "1")
    config = from_environment()

    with pytest.raises(RuntimeError, match="Migrations run in development only"):
        if action == "upgrade":
            command.upgrade(config, "head")
        elif action == "downgrade":
            command.downgrade(config, "base")
        elif action == "check":
            command.check(config)
        elif action == "current":
            command.current(config)
        else:
            command.stamp(config, "head")

    assert public_tables(engine) == set()


def test_migrations_need_a_database_address(
    clean_environment: pytest.MonkeyPatch,
) -> None:
    with pytest.raises(RuntimeError, match="DATABASE_URL is not set"):
        command.upgrade(from_environment(), "head")


def test_migrations_are_found_from_any_working_directory(
    fresh: tuple[str, Engine], tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    url, engine = fresh
    monkeypatch.chdir(tmp_path)

    command.upgrade(alembic_config(url), "head")

    assert public_tables(engine) == APPLICATION_TABLES | {"alembic_version"}
    assert list(tmp_path.iterdir()) == []


