def _rows(engine: Engine, sql: str) -> list[Any]:
    with engine.connect() as connection:
        return list(connection.execute(text(sql)))


def test_downgrade_removes_the_tables_and_upgrade_brings_them_back(
    fresh: tuple[str, Engine],
) -> None:
    url, engine = fresh
    config = alembic_config(url)

    command.upgrade(config, "head")
    command.downgrade(config, "base")

    assert public_tables(engine) == {"alembic_version"}
    assert scalar(engine, "SELECT count(*) FROM alembic_version") == 0
    assert scalar(engine, "SELECT count(*) FROM pg_indexes WHERE schemaname = 'public'") == 1

    command.upgrade(config, "head")

    assert public_tables(engine) == APPLICATION_TABLES | {"alembic_version"}
    command.check(config)


def test_running_the_migrations_twice_changes_nothing(fresh: tuple[str, Engine]) -> None:
    url, engine = fresh
    config = alembic_config(url)

    command.upgrade(config, "head")
    command.upgrade(config, "head")

    assert public_tables(engine) == APPLICATION_TABLES | {"alembic_version"}
    assert scalar(engine, "SELECT count(*) FROM alembic_version") == 1


def test_the_revisions_form_one_line(database_url: str) -> None:
    scripts = ScriptDirectory.from_config(alembic_config(database_url))

    assert scripts.get_heads() == ["0006"]
    assert scripts.get_bases() == ["0001"]
    revisions = list(scripts.walk_revisions())
    assert [revision.revision for revision in revisions] == [
        "0006",
        "0005",
        "0004",
        "0003",
        "10af905d740f",
        "0001",
    ]
    # Alembic follows the revision chain, not lexical filename order.
    assert sorted(path.name for path in VERSIONS.glob("*.py")) == [
        "0001_users_sessions_audit.py",
        "0003_committee.py",
        "0004_owner_proposals.py",
        "0005_strategy_lab.py",
        "0006_strategy_backtest_reviews.py",
        "10af905d740f_phase2_fund_ledger_market_data.py",
    ]


def test_the_sql_can_be_printed_instead_of_run(fresh: tuple[str, Engine]) -> None:
    url, engine = fresh
    config = alembic_config(url)
    config.output_buffer = io.StringIO()

    command.upgrade(config, "head", sql=True)

    sql = config.output_buffer.getvalue()
    for table in APPLICATION_TABLES:
        assert f"CREATE TABLE {table} (" in sql
    assert "TIMESTAMP WITH TIME ZONE" in sql
    assert "TIMESTAMP WITHOUT TIME ZONE" not in sql
    # Nothing was run.
    assert public_tables(engine) == set()


